// 二阶卡尔曼滤波
double second_order_exkalman_filter(k_filter *EXk_flt, second_order_struct *second_struct, double input)
{
    second_struct->current_output = (second_struct->a) * input + (second_struct->b) * (second_struct->last_output) - (second_struct->c) * (second_struct->last_last_output); // 计算出本次滤波输出
    second_struct->last_last_output = second_struct->last_output;                                                                                                            // 更新上上次输出
    exkalman_filte_b = second_struct->current_output - second_struct->last_output;
    second_struct->last_output = second_struct->current_output; // 更新上次输出
    //	k_flt->input=IIR_filter(&IIR_flt,input); //一阶滞后滤波法获得测量值,
    // 如果滞后很强就用下面的
    /*量测方程的更新，3组方程*/
    EXk_flt->input = input;
    EXk_flt->kg = (EXk_flt->C_last) / (EXk_flt->C_last + EXk_flt->R);                                                      /*计算卡尔曼增益 kg(k) = C(k|k-1)*H(转置)/[H*C(k|k-1)*H(转置)+R] */
    EXk_flt->X = EXk_flt->X_last + exkalman_filte_b + EXk_flt->kg * (EXk_flt->input - EXk_flt->X_last - exkalman_filte_b); /*得到现在状态的最优化估算值 X(k|k) = X(k|k-1)+kg(k)*[Z(k)-H*X(k|k-1)]*/
    EXk_flt->C = (1 - EXk_flt->kg) * (EXk_flt->C_last);                                                                    /*更新 k 状态下 X(k|k) 的协方差 C(k|k) =[I-kg(k)*H]*C(k|k-1) */
    /*时间更新方程，2组方程*/
    EXk_flt->X_last = EXk_flt->X;              /*根据上一状态预测下一状态的结果 X(k+1|k) = A*X(k|k) 没有控制量*/
    EXk_flt->C_last = EXk_flt->C + EXk_flt->Q; /*更新 X(k|k-1) 的协方差 C(k+1|k) = A*C(k|k)*A(转置)+B*Q*B(转置)*/

    return EXk_flt->X; // 返回卡尔曼滤波后的值
}

